"""Gap G0 of docs/paper/paper_draft.md: refine the recorded R2a endpoints the basin run left out.

The basin run refined endpoints with 4 < ΔD <= 1e5 only, so the S1* distribution it reports is cut
at S1 >= 10 below and is silent about parameter-distinct endpoints that already sit within ΔD <= 4 of
the truth. This script takes every recorded R2a endpoint with ΔD <= 4 whose largest bound-scaled
parameter distance from the truth exceeds DIST_MIN, and refines it with the basin run's own code
(`basin.refine`, same budget and convergence tests, no new start). Results go to
docs/fisher_global/near_full/, one file per endpoint.

    <venv python> -I experiments/005_fisher_global/g0_near.py candidates
    <venv python> -I experiments/005_fisher_global/g0_near.py run --worker 0
    <venv python> -I experiments/005_fisher_global/g0_near.py report
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "experiments" / "001_identifiability"))
import basin  # noqa: E402
import scan  # noqa: E402

OUT = ROOT / "docs" / "fisher_global"
NEAR_DIR = OUT / "near_full"
CANDS = OUT / "near_candidates.json"
REPORT = OUT / "near_report.md"
DIST_MIN = 1e-3  # fraction of the box width


def candidates() -> None:
    rows = []
    for path in sorted((ROOT / "docs" / "identifiability" / "scan").glob("fits_*.json")):
        d = json.loads(path.read_text(encoding="utf-8"))
        free, p0 = d["free"], d["truth"]
        _, _, bounds = scan.setup(d["condition"])
        for e in d["endpoints"]:
            if e["deviance"] > basin.REACH:
                continue
            dist = max(abs(e["params"][k] - p0[k]) / (bounds[k][1] - bounds[k][0]) for k in free)
            if dist > DIST_MIN:
                rows.append(
                    {
                        "id": f"r2a:{d['index']:02d}:{e['start']:02d}",
                        "cond": d["index"],
                        "start": e["start"],
                        "dD": e["deviance"],
                        "dist": dist,
                    }
                )
    CANDS.write_text(
        json.dumps({"dist_min": DIST_MIN, "r2a": rows}, indent=1) + "\n", encoding="utf-8"
    )
    print(f"{len(rows)} candidates")


def run(worker: int) -> None:
    basin.FULL_DIR = NEAR_DIR
    basin.CANDIDATES = CANDS
    basin.full_run("r2a", None, ("nf",), False, worker, None)


def report() -> None:
    cand = {c["id"]: c for c in json.loads(CANDS.read_text(encoding="utf-8"))["r2a"]}
    res = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(NEAR_DIR.glob("*__nf.json"))]
    secs = sum(r["seconds"] for r in res)
    conf = [r for r in res if r["outcome"] == "confirmed"]
    def back(r: dict) -> bool:
        d = json.loads(
            (ROOT / "docs" / "identifiability" / "scan" / f"fits_{r['id'].split(':')[1]}.json").read_text(
                encoding="utf-8"
            )
        )
        w = np.array(r["hi"]) - np.array(r["lo"])
        t = np.array([d["truth"][k] for k in r["names"]])
        return bool((np.abs(np.array(r["x_min"]) - t) / w).max() < DIST_MIN)

    returned = sum(back(r) for r in conf)
    lines = [
        "# G0: refinement of the recorded R2a endpoints within ΔD <= 4 of the truth",
        "",
        "Generated by `experiments/005_fisher_global/g0_near.py report`. Same refinement code and budget "
        "as the basin run (`basin.refine`); no new start. Candidates are endpoints with ΔD <= 4 whose "
        f"largest bound-scaled parameter distance from the truth exceeds {DIST_MIN:g}.",
        "",
        f"- candidates {len(cand)}, refined {len(res)}, confirmed minima {len(conf)}",
        f"- minima back at the truth (largest bound-scaled distance below {DIST_MIN:g}): {returned}; "
        f"a second minimum: {len(conf) - returned}",
        f"- CPU time {secs / 3600:.2f} h (mean {secs / max(len(res), 1):.0f} s per endpoint)",
        "",
        "| minimum ΔD from the truth | endpoints | S1* (counts at R = 1) |",
        "|---|---|---|",
    ]
    bins = [(0, 1e-3), (1e-3, 1.0), (1.0, 4.0), (4.0, np.inf)]
    for lo, hi in bins:
        sel = [r for r in conf if lo < r["dnf_min"] <= hi or (lo == 0 and r["dnf_min"] == 0)]
        s1 = [r["S1_min"] for r in sel if r["S1_min"]]
        rng = f"{min(s1):.3g} to {max(s1):.3g}" if s1 else "n/a"
        lines.append(f"| {lo:g} to {hi:g} | {len(sel)} | {rng} |")
    lines += ["", "Unconfirmed: " + (", ".join(r["id"] for r in res if r["outcome"] != "confirmed") or "none")]
    lines += ["", "| id | start ΔD | minimum ΔD | S1* | outcome | seconds |", "|---|---|---|---|---|---|"]
    for r in sorted(res, key=lambda r: -r["dnf_min"]):
        s1 = f"{r['S1_min']:.3g}" if r["S1_min"] else "n/a"
        lines.append(
            f"| {r['id']} | {cand[r['id']]['dD']:.3g} | {r['dnf_min']:.3g} | {s1} | "
            f"{r['outcome']} | {r['seconds']:.0f} |"
        )
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:14]).encode("ascii", "replace").decode())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["candidates", "run", "report"])
    ap.add_argument("--worker", type=int, default=0)
    args = ap.parse_args()
    {"candidates": candidates, "run": lambda: run(args.worker), "report": report}[args.mode]()


if __name__ == "__main__":
    main()
