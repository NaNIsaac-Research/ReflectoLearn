"""Tables and the compute budget from the basin pilot (PREREG-BASIN section 6); no verdict.

.venv/Scripts/python.exe -I experiments/005_fisher_global/basin_pilot_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[2] / "docs" / "fisher_global"
REGIONS = ["low"] + [f"b{i}" for i in range(10)]
N_MAX = 3000
FULL = {"r2a": 749, "x2e": 93}


def curve_dev(lam: np.ndarray, mu: np.ndarray) -> float:
    r = lam / mu - 1
    small = np.abs(r) < 1e-3
    rs = np.where(small, r, 0.0)
    series = rs**2 / 2 - rs**3 / 3 + rs**4 / 4 - rs**5 / 5
    direct = r - np.log1p(np.where(small, 0.0, r))
    return float((2 * mu * np.where(small, series, direct)).sum())


def g(x, fmt=".3g") -> str:
    return "—" if x is None else format(x, fmt)


def main() -> None:
    rows = [json.loads(x) for x in (OUT / "basin_pilot.jsonl").read_text().splitlines()]
    lines = [
        "# Basin pilot tables (generated by basin_pilot_report.py; do not edit)",
        "",
        (
            "PREREG-BASIN.md section 6. [pilot] numbers, not used for any verdict. ΔD_nf against the"
            " truth's noise-free counts; κ = ΔD_nf(end) / ΔD_nf(min); ρ = ΔD_F / ΔD_nf; top = region"
            " with the largest deviance share (291-point grids only)."
        ),
        "",
        "## Refinements",
        "",
        (
            "| id | obj | outcome | on bound | nfev | stages | model / value / Hessian calls | s"
            " | peak MB | start check | D end → final | ΔD_nf end → min | κ | S₁ end → min"
            " | ρ end → min | top end → min | drift (u) |"
        ),
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        c = r["final_checks"]
        bound = ", ".join(c["at_lo"] + c["at_hi"]) or "—"
        top = "—"
        if "share_min" in r:
            top = f"{REGIONS[int(np.argmax(r['share_end']))]} → {REGIONS[int(np.argmax(r['share_min']))]}"
        lines.append(
            f"| {r['id']} | {r['objective']} | {r['outcome']} | {bound} | {r['nfev_total']}"
            f" | {len(r['stages'])} | {r['model_calls']} / {r['value_calls']} / {r['hessian_calls']}"
            f" | {r['seconds']:.0f} | {r['peak_mb']:.0f} | {r['start_check_rel']:.1e}"
            f" | {r['d_recorded']:.4g} → {r['d_final']:.4g} | {r['dnf_end']:.4g} → {r['dnf_min']:.4g}"
            f" | {g(r['kappa'])} | {g(r['S1_end'])} → {g(r['S1_min'])}"
            f" | {g(r.get('rho_end'))} → {g(r.get('rho_min'))} | {top} | {r['drift_inf']:.2g} |"
        )

    lines += [
        "",
        "## Convergence tests at the final point",
        "",
        (
            "| id | obj | τ | decrement | weak grad | weak dirs | min eig / max | probe min | KKT"
            " | stage statuses |"
        ),
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        c = r["final_checks"]
        st = " ".join(str(s["status"]) + ("c" if s["confirmation"] else "") for s in r["stages"])
        lines.append(
            f"| {r['id']} | {r['objective']} | {c['tau']:.2g} | {g(c['decrement'], '.2g')}"
            f" | {g(c['weak_grad'], '.2g')} | {c['n_weak']} | {g(c.get('eig_min_rel'), '.2g')}"
            f" | {g(c.get('probe_min'), '.2g')} | {c['kkt']} | {st} |"
        )

    lines += ["", "## Deviance by stage", ""]
    for r in rows:
        ds = " → ".join(f"{s['d_after']:.4g}" for s in r["stages"])
        lines.append(f"- {r['id']} {r['objective']}: {r['d_recorded']:.4g} → {ds}")

    by = {(r["id"], r["objective"]): r for r in rows}
    a, b = by.get(("r2a:06:44", "nf")), by.get(("r2a:06:11", "nf"))
    lines += ["", "## Duplicate relation of r2a:06:44 and r2a:06:11", ""]
    if a and b:
        names = a["names"]
        for tag in ("end", "min"):
            d = np.abs(np.subtract(a[f"x_{tag}"], b[f"x_{tag}"]))
            k = int(np.argmax(d))
            lines.append(f"- x_{tag}: largest parameter difference {names[k]} {d[k]:.3g}")
        la, lb = np.asarray(a["lam_min"]), np.asarray(b["lam_min"])
        lines.append(
            f"- minima: max(ΔD(a|b), ΔD(b|a)) = {max(curve_dev(la, lb), curve_dev(lb, la)):.3g}"
            f" (same basin if ≤ 1, and only if both are confirmed); outcomes {a['outcome']}"
            f" / {b['outcome']}"
        )
    else:
        lines.append("- not both refined")

    lines += [
        "",
        "## Compute budget for the full run (extrapolated from the pilot)",
        "",
        (
            "Seconds per evaluation from the pilot's TRF stages; worst case = every candidate spends"
            " N_max = 3000 evaluations plus the pilot's largest test overhead per candidate. Wall time"
            " for p processes assumes linear scaling (no shared state; one torch thread each)."
        ),
        "",
        (
            "| set | n | s per eval, median [max] | s per candidate, pilot median, mean [max] | test overhead s, max"
            " | total CPU h, pilot mean | total CPU h, worst | wall h at 1 / 2 / 4 proc (mean; worst)"
            " | peak MB per proc |"
        ),
        "|---|---|---|---|---|---|---|---|---|",
    ]
    sets = [("r2a", "nf", FULL["r2a"]), ("x2e", "nf", FULL["x2e"]), ("x2e", "tr", FULL["x2e"])]
    total_mean = total_worst = 0.0
    peaks = []
    for src, obj, n in sets:
        sel = [r for r in rows if r["id"].startswith(src) and r["objective"] == obj]
        if not sel:
            lines.append(f"| {src} {obj} | {n} | not run | | | | | | |")
            continue
        per_eval = [sum(s["seconds"] for s in r["stages"]) / max(r["nfev_total"], 1) for r in sel]
        overhead = [r["seconds"] - sum(s["seconds"] for s in r["stages"]) for r in sel]
        secs = [r["seconds"] for r in sel]
        mean = float(np.mean(secs)) * n / 3600
        worst = (N_MAX * max(per_eval) + max(overhead)) * n / 3600
        total_mean += mean
        total_worst += worst
        peaks += [r["peak_mb"] for r in sel]
        walls = " / ".join(f"{mean / p:.2g}; {worst / p:.2g}" for p in (1, 2, 4))
        lines.append(
            f"| {src} {obj} | {n} | {np.median(per_eval):.3f} [{max(per_eval):.3f}]"
            f" | {np.median(secs):.0f}, {np.mean(secs):.0f} [{max(secs):.0f}] | {max(overhead):.0f} | {mean:.2g}"
            f" | {worst:.2g} | {walls} | {max(r['peak_mb'] for r in sel):.0f} |"
        )
    walls = " / ".join(f"{total_mean / p:.2g}; {total_worst / p:.2g}" for p in (1, 2, 4))
    lines.append(
        f"| all | {sum(n for _, _, n in sets)} | | | | {total_mean:.2g} | {total_worst:.2g} | {walls}"
        f" | {max(peaks) if peaks else 0:.0f} |"
    )
    (OUT / "basin_pilot.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'basin_pilot.md'}")


if __name__ == "__main__":
    main()
