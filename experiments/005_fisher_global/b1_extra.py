"""Post-hoc descriptions of B-1 (outside the registered verdicts of PREREG.md).

Reads docs/fisher_global/b1.json and the R2a endpoint files; writes b1_extra.md. Forward model only
for the line search along near endpoints' displacements.

    .venv/Scripts/python.exe -I experiments/005_fisher_global/b1_extra.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "001_identifiability"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import scan  # noqa: E402
from b1 import OUT, REACH, SCAN_DIR, W2_CONDITIONS, counts, deviance_terms  # noqa: E402

torch.set_num_threads(1)
res = json.loads((OUT / "b1.json").read_text(encoding="utf-8"))
lines = [
    "# B-1 post-hoc descriptions (generated by b1_extra.py; outside the registered verdicts)",
    "",
]

lines += [
    "## Near endpoints (ΔD ≤ 4) with ρ outside [0.5, 2]",
    "",
    "Δθ in units of the bound width; the three largest components. Line: ΔD along θ_t + t Δθ,"
    " t = 0.25, 0.5, 0.75, 1, against the Fisher quadratic t² ΔD_F.",
    "",
    "| # | start | at cap | ΔD | ΔD_F | ρ | largest \\|Δθ\\|/width | ΔD(t)/ΔD_F(t) at t = 0.25, 0.5, 0.75, 1 |",
    "|---|---|---|---|---|---|---|---|",
]
outliers = []
for c in res["conditions"]:
    data = json.loads((SCAN_DIR / f"fits_{c['index']:02d}.json").read_text(encoding="utf-8"))
    p0, free = data["truth"], tuple(data["free"])
    _, _, bounds = scan.setup(data["condition"])
    q = scan.q_grid(data["condition"]["tth_max"])
    lam_t = counts(q, p0)
    width = np.array([bounds[k][1] - bounds[k][0] for k in free])
    theta_t = np.array([p0[k] for k in free])
    by_start = {e["start"]: e for e in data["endpoints"]}
    for r in c["rows"]:
        if r["dD"] > REACH or 0.5 <= r["rho"] <= 2:
            continue
        e = by_start[r["start"]]
        dtheta = np.array([e["params"][k] for k in free]) - theta_t
        u = np.abs(dtheta) / width
        top = np.argsort(u)[::-1][:3]
        ratios = []
        for t in (0.25, 0.5, 0.75, 1.0):
            lam = counts(q, p0 | dict(zip(free, (theta_t + t * dtheta).tolist(), strict=True)))
            ratios.append(deviance_terms(lam, lam_t).sum() / (t**2 * r["dF"]))
        outliers.append((c["index"], free, dtheta, width))
        lines.append(
            f"| {c['index']} | {r['start']} | {'yes' if r['nfev'] >= scan.MAX_NFEV else 'no'}"
            f" | {r['dD']:.2g} | {r['dF']:.3g} | {r['rho']:.3g} | "
            + ", ".join(f"{free[i]} {u[i]:.2g}" for i in top)
            + " | "
            + ", ".join(f"{x:.2g}" for x in ratios)
            + " |"
        )

near_ok = [
    r for c in res["conditions"] for r in c["rows"] if r["dD"] <= REACH and 0.5 <= r["rho"] <= 2
]
lines += [
    "",
    f"Near endpoints inside [0.5, 2]: {len(near_ok)}; ΔD median {np.median([r['dD'] for r in near_ok]):.2g},"
    f" max {max(r['dD'] for r in near_ok):.2g}.",
    "",
]
near_all = [r for c in res["conditions"] for r in c["rows"] if r["dD"] <= REACH]
wrong_all = [r for c in res["conditions"] for r in c["rows"] if r["dD"] > REACH]
lines += [
    "Same side of Δχ² = 4: near endpoints with ΔD_F > 4:"
    f" {sum(r['dF'] > REACH for r in near_all)} of {len(near_all)}; outside [0.5, 2] with ΔD_F < 1:"
    f" {sum(not 0.5 <= r['rho'] <= 2 and r['dF'] < 1 for r in near_all)}; wrong endpoints with"
    f" ΔD_F ≤ 4: {sum(r['dF'] <= REACH for r in wrong_all)} of {len(wrong_all)}.",
    "",
]

wrong = [(c, r) for c in res["conditions"] for r in c["rows"] if r["dD"] > REACH]
cap = [r for _, r in wrong if r["nfev"] >= scan.MAX_NFEV]
free_end = [r for _, r in wrong if r["nfev"] < scan.MAX_NFEV]
lines += [
    "## Wrong endpoints: at the evaluation cap or not",
    "",
    "| | n | ΔD, median | S₁, median | ρ, median | share ρ ≥ 10 |",
    "|---|---|---|---|---|---|",
]
for name, sel in (("at cap (200)", cap), ("stopped before cap", free_end)):
    lines.append(
        f"| {name} | {len(sel)} | {np.median([r['dD'] for r in sel]):.3g}"
        f" | {np.median([r['S1'] for r in sel]):.3g} | {np.median([r['rho'] for r in sel]):.3g}"
        f" | {np.mean([r['rho'] >= 10 for r in sel]):.2f} |"
    )

w2 = [(c, r) for c, r in wrong if c["index"] in W2_CONDITIONS]
lines += [
    "",
    "## H-W2 test set, subsets",
    "",
    "| subset | n | (a) | (b) | median share low, b0, b1, b2, b3 |",
    "|---|---|---|---|---|",
]
subsets = {
    "all": w2,
    "stopped before cap": [(c, r) for c, r in w2 if r["nfev"] < scan.MAX_NFEV],
    "ΔD ≤ 10⁴ (S₁ ≥ 100)": [(c, r) for c, r in w2 if r["dD"] <= 1e4],
    "ΔD ≤ 10⁵ (S₁ ≥ 10)": [(c, r) for c, r in w2 if r["dD"] <= 1e5],
}
for name, sel in subsets.items():
    if not sel:
        lines.append(f"| {name} | 0 | — | — | — |")
        continue
    s = np.array([r["share"] for _, r in sel])
    lines.append(
        f"| {name} | {len(sel)} | {np.mean(s[:, :6].sum(1) >= 0.9):.2f}"
        f" | {np.mean(np.isin(np.argmax(s, 1), (1, 2, 3))):.2f} | "
        + ", ".join(f"{v:.3f}" for v in np.median(s[:, :5], 0))
        + " |"
    )

(OUT / "b1_extra.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT / 'b1_extra.md'}")
