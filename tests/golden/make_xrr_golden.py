"""Write xrr.json: layer stacks and their exact reflectivity, shared by every XRR engine's tests.

The curves come from ``reflectolearn.benchmark.parratt`` in float64 (no absorption guard), so an
engine that matches them to ~1e-10 in log10 R computes the same physics. The JS engine on
NaNIsaac.github.io (xrr.js) tests against a copy of this file.

    uv run python tests/golden/make_xrr_golden.py
"""

import json
from pathlib import Path

import numpy as np

from reflectolearn.benchmark import SI, SIO2, parratt

OUT = Path(__file__).with_name("xrr.json")
Q = np.linspace(0.005, 0.6, 240)


def _stacks():
    yield "bare Si", [(0j, 0.0, 0.0), (20.07 + 0j, 0.0, 0.0)]
    yield "rough Si", [(0j, 0.0, 0.0), (SI, 0.0, 5.0)]
    yield (
        "absorbing film on SiO2 on Si",
        [(0j, 0.0, 0.0), (45 + 2j, 250.0, 6.0), (SIO2, 15.0, 3.0), (SI, 0.0, 4.0)],
    )
    rng = np.random.default_rng(7)
    for k in range(4):
        n = int(rng.integers(1, 5))
        films = [
            (
                complex(rng.uniform(5, 60), rng.uniform(0, 2)),
                rng.uniform(20, 300),
                rng.uniform(0, 8),
            )
            for _ in range(n)
        ]
        yield f"random {k}", [(0j, 0.0, 0.0), *films, (SI, 0.0, rng.uniform(0, 8))]


def build() -> dict:
    stacks = []
    for name, layers in _stacks():
        stacks.append(
            {
                "name": name,
                "layers": [
                    {"sld": [s.real, s.imag], "thickness": float(d), "roughness": float(r)}
                    for s, d, r in layers
                ],
                "R": parratt(Q, layers).tolist(),
            }
        )
    return {
        "about": "Exact specular reflectivity for XRR engine tests; generated by "
        "ReflectoLearn tests/golden/make_xrr_golden.py (benchmark.parratt, float64).",
        "units": {
            "q": "1/Angstrom",
            "sld": "1e-6/Angstrom^2, [real, imag], imag > 0 absorbs",
            "thickness": "Angstrom",
            "roughness": "Angstrom, rms, Nevot-Croce",
        },
        "layout": "layers from the ambient down to the substrate; roughness is each layer's top "
        "interface; the ambient's and substrate's thickness are 0",
        "q": Q.tolist(),
        "stacks": stacks,
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
